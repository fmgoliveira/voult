/** Name of the file under `~/.ssh/voult/` and the line that pulls it into `~/.ssh/config`. */
export const INCLUDE_LINE = 'Include voult/config';
export const INCLUDE_MARKER =
  '# Voult: managed hosts. Keep this Include first; delete both lines to stop using them.';
export const GENERATED_HEADER =
  '# Generated by Voult from your vault. Edit the host in Voult, not here: this file is rewritten on every sync.';

/** Options that can run a program; they are ignored unless the user turns them on. */
const COMMAND_OPTIONS = new Set([
  'proxycommand',
  'localcommand',
  'permitlocalcommand',
  'knownhostscommand',
  'pkcs11provider',
  'securitykeyprovider',
]);
/**
 * Every keyword ssh_config(5) knows. An unknown one makes ssh refuse to run for *all* hosts
 * ("Bad configuration option"), so anything else is dropped with a warning.
 */
const KNOWN_OPTIONS = new Set(
  (
    'addkeystoagent addressfamily batchmode bindaddress bindinterface canonicaldomains ' +
    'canonicalizefallbacklocal canonicalizehostname canonicalizemaxdots canonicalizepermittedcnames ' +
    'casignaturealgorithms certificatefile challengeresponseauthentication checkhostip ciphers ' +
    'clearallforwardings compression connectionattempts connecttimeout controlmaster controlpath ' +
    'controlpersist dynamicforward enableescapecommandline enablesshkeysign escapechar ' +
    'exitonforwardfailure fingerprinthash forkafterauthentication forwardagent forwardx11 ' +
    'forwardx11timeout forwardx11trusted gatewayports globalknownhostsfile gssapiauthentication ' +
    'gssapidelegatecredentials hashknownhosts hostbasedacceptedalgorithms hostbasedauthentication ' +
    'hostkeyalgorithms hostkeyalias hostname identitiesonly identityagent identityfile ipqos ' +
    'kbdinteractiveauthentication kbdinteractivedevices kexalgorithms knownhostscommand localcommand ' +
    'localforward loglevel logverbose macs nohostauthenticationforlocalhost numberofpasswordprompts ' +
    'obscurekeystroketiming passwordauthentication permitlocalcommand permitremoteopen ' +
    'pkcs11provider port preferredauthentications proxycommand proxyjump proxyusefdpass ' +
    'pubkeyacceptedalgorithms pubkeyauthentication rekeylimit remotecommand remoteforward requesttty ' +
    'requiredrsasize revokedhostkeys securitykeyprovider sendenv serveralivecountmax ' +
    'serveraliveinterval sessiontype setenv stdinnull streamlocalbindmask streamlocalbindunlink ' +
    'stricthostkeychecking syslogfacility tcpkeepalive tag tunnel tunneldevice updatehostkeys user ' +
    'userknownhostsfile verifyhostkeydns visualhostkey xauthlocation'
  ).split(' '),
);
/** Options that would break out of the Host block. */
const STRUCTURE_OPTIONS = new Set(['host', 'match', 'include']);

export interface RenderOptions {
  /** Let `ProxyCommand`, `LocalCommand` … through (default: dropped with a warning). */
  allowCommandOptions?: boolean;
}

export interface RenderResult {
  config: string;
  /** `<name>.pub` → file contents, for every key a rendered host uses. */
  publicKeys: Map<string, string>;
  /** Aliases that were written. */
  hosts: string[];
  warnings: string[];
}

/** File name (no directory) for a key's public half. Filesystem-safe form of its fingerprint. */
export const publicKeyFileName = (fingerprint: string): string =>
  fingerprint
    .replace(/^SHA256:/, '')
    .replace(/\//g, '_')
    .replace(/\+/g, '-') + '.pub';

const HOSTNAME_RE = /^[A-Za-z0-9._:%\-[\]]+$/;
const USER_RE = /^[A-Za-z0-9._\-@$\\]+$/;
const JUMP_ELEMENT_RE = /^[A-Za-z0-9._\-@:[\]%\\]+$/;
const OPTION_RE = /^([A-Za-z][A-Za-z0-9]*)(\s+|\s*=\s*)(\S.*)$/;

interface Live<T> {
  id: string;
  item: T;
}

/** Turn the vault's SSH items into the contents of `~/.ssh/voult/config` and its `.pub` files. */
export function renderConfig(items: ItemView[], opts: RenderOptions = {}): RenderResult {
  const warnings: string[] = [];
  const live = items.filter((v) => v.deletedAt === null);
  const keys = new Map<string, Live<SshKeyItem>>();
  const hosts: Live<SshHostItem>[] = [];
  for (const v of live) {
    if (v.item.type === 'sshKey') keys.set(v.id, { id: v.id, item: v.item });
    else if (v.item.type === 'sshHost') hosts.push({ id: v.id, item: v.item });
  }

  // Only well-formed, unique aliases are written.
  const seen: string[] = [];
  const valid: Live<SshHostItem>[] = [];
  for (const h of hosts.sort((a, b) => a.item.alias.localeCompare(b.item.alias))) {
    const bad = validateAlias(h.item.alias, seen);
    if (bad) {
      warnings.push(`Skipped "${h.item.title || h.item.alias}": its alias is ${bad}.`);
      continue;
    }
    if (!h.item.hostname || !HOSTNAME_RE.test(h.item.hostname)) {
      warnings.push(
        `Skipped "${h.item.alias}": the host name has characters ssh config cannot hold.`,
      );
      continue;
    }
    seen.push(h.item.alias);
    valid.push(h);
  }
  const aliases = new Set(seen);

  const publicKeys = new Map<string, string>();
  const blocks: string[] = [];
  const written: string[] = [];
  for (const { item: h } of valid) {
    const lines = [`Host ${h.alias}`, `  HostName ${h.hostname}`, `  Port ${h.port}`];
    if (h.username) {
      if (USER_RE.test(h.username)) lines.push(`  User ${h.username}`);
      else warnings.push(`"${h.alias}": the user name was ignored (unsupported characters).`);
    }
    if (h.proxyJump) {
      const jump = renderJump(h.proxyJump, aliases);
      if (jump) lines.push(`  ProxyJump ${jump}`);
      else warnings.push(`"${h.alias}": the jump host was ignored (unsupported characters).`);
    }

    if (hostUsesKey(h)) {
      const k = h.keyItemId ? keys.get(h.keyItemId) : undefined;
      if (!k) {
        warnings.push(
          `"${h.alias}": its key was not found, so it will fall back to the agent's keys.`,
        );
      } else {
        try {
          const fp = fingerprintSha256(publicKeyBlob(k.item.publicKey));
          const file = publicKeyFileName(fp);
          const body = k.item.publicKey.trim().split(/\s+/).slice(0, 2).join(' ');
          publicKeys.set(
            file,
            `${body}${k.item.comment ? ' ' + k.item.comment.replace(/\s+/g, ' ') : ''}\n`,
          );
          lines.push(`  IdentityFile ~/.ssh/voult/${file}`, '  IdentitiesOnly yes');
        } catch {
          warnings.push(`"${h.alias}": its key has an unreadable public key.`);
        }
      }
    }
    if (h.auth === 'password') {
      // Without this ssh first offers every agent key and can hit "too many authentication failures".
      lines.push(
        '  PubkeyAuthentication no',
        '  PreferredAuthentications password,keyboard-interactive',
      );
    } else if (h.auth === 'keyAndPassword') {
      lines.push('  PreferredAuthentications publickey,password,keyboard-interactive');
    }

    for (const raw of h.extraOptions.split(/\r?\n/)) {
      const line = raw.trim();
      if (!line || line.startsWith('#')) continue;
      const m = OPTION_RE.exec(line);
      if (!m) {
        warnings.push(
          `"${h.alias}": the option "${line.slice(0, 40)}" was ignored (not "Key value").`,
        );
        continue;
      }
      const key = m[1]!.toLowerCase();
      if (STRUCTURE_OPTIONS.has(key)) {
        warnings.push(`"${h.alias}": ${m[1]} cannot be used in extra options.`);
      } else if (!KNOWN_OPTIONS.has(key)) {
        warnings.push(`"${h.alias}": "${m[1]}" is not an ssh option, so it was ignored.`);
      } else if (COMMAND_OPTIONS.has(key) && !opts.allowCommandOptions) {
        warnings.push(
          `"${h.alias}": ${m[1]} runs a program, so it was ignored. Turn it on with \`voult config allowCommandOptions on\`.`,
        );
      } else {
        lines.push(`  ${m[1]} ${m[3]}`);
      }
    }
    blocks.push(lines.join('\n'));
    written.push(h.alias);
  }

  const config = [GENERATED_HEADER, '', ...blocks.map((b) => b + '\n')].join('\n');
  return {
    config: blocks.length ? config : GENERATED_HEADER + '\n',
    publicKeys,
    hosts: written,
    warnings,
  };
}

/** `a,b` where each is a known alias or a `user@host[:port]`; null if anything is unusable. */
function renderJump(value: string, aliases: Set<string>): string | null {
  const parts = value.split(',').map((p) => p.trim());
  if (parts.some((p) => !p || !JUMP_ELEMENT_RE.test(p) || p.startsWith('-'))) return null;
  void aliases; // an alias stays as written: ssh resolves it from this same config
  return parts.join(',');
}

// ------------------------------------------------------------------ Include handling

/**
 * Make `Include voult/config` the first line of the user's ssh config (an Include only applies
 * to what comes after the Host blocks if it is before them). Everything else is left exactly as
 * it was; returns the same text when it is already in place.
 */
export function ensureInclude(text: string): string {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const isInclude = (l: string) => /^\s*Include\s+voult\/config\s*$/i.test(l);
  const lines = text.split(/\r?\n/);
  const first = lines.findIndex((l) => l.trim() !== '');
  if (first >= 0) {
    if (isInclude(lines[first]!)) return text;
    if (lines[first]!.trim() === INCLUDE_MARKER && isInclude(lines[first + 1] ?? '')) return text;
  }
  // Drop our lines from wherever they were (an Include below a Host block would not work), keeping
  // every other byte, then put them on top.
  const stripped = text
    .split(/(?<=\n)/)
    .filter((l) => l.trim() !== INCLUDE_MARKER && !isInclude(l))
    .join('');
  return `${INCLUDE_MARKER}${eol}${INCLUDE_LINE}${eol}${stripped.trim() ? eol + stripped : ''}`;
}

// ------------------------------------------------------------------ files

const KEY_FILE_RE = /^[A-Za-z0-9_-]{43}\.pub$/;

/** Restrict a directory to the current user, SYSTEM and Administrators (OpenSSH insists). */
export type LockDown = (dir: string) => Promise<void>;

export const windowsLockDown: LockDown = (dir) =>
  new Promise((resolve) => {
    const user = process.env.USERNAME;
    if (process.platform !== 'win32' || !user) return resolve();
    execFile(
      'icacls.exe',
      [
        dir,
        '/inheritance:r',
        '/grant:r',
        `${user}:(OI)(CI)F`,
        '*S-1-5-18:(OI)(CI)F', // SYSTEM
        '*S-1-5-32-544:(OI)(CI)F', // Administrators
      ],
      { windowsHide: true },
      () => resolve(), // best effort: a failure leaves the inherited (already user-private) ACL
    );
  });

function writeIfChanged(file: string, content: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return false;
  const tmp = `${file}.tmp`;
  writeFileSync(tmp, content, { mode: 0o600 });
  renameSync(tmp, file);
  return true;
}

export interface WriteResult extends RenderResult {
  changed: boolean;
  dir: string;
}

/** Write `~/.ssh/voult/config`, the `.pub` files, and make sure the Include is in place. */
export async function writeSshConfig(
  sshDir: string,
  items: ItemView[],
  opts: RenderOptions & { lockDown?: LockDown } = {},
): Promise<WriteResult> {
  const dir = path.join(sshDir, 'voult');
  mkdirSync(dir, { recursive: true });
  const r = renderConfig(items, opts);
  let changed = writeIfChanged(path.join(dir, 'config'), r.config);
  for (const [name, body] of r.publicKeys)
    changed = writeIfChanged(path.join(dir, name), body) || changed;
  for (const f of readdirSync(dir)) {
    if (KEY_FILE_RE.test(f) && !r.publicKeys.has(f)) {
      rmSync(path.join(dir, f), { force: true });
      changed = true;
    }
  }
  await (opts.lockDown ?? windowsLockDown)(dir);

  const main = path.join(sshDir, 'config');
  const before = existsSync(main) ? readFileSync(main, 'utf8') : '';
  const after = ensureInclude(before);
  if (after !== before) {
    writeFileSync(main, after);
    try {
      chmodSync(main, 0o600);
    } catch {
      /* not meaningful on Windows */
    }
    changed = true;
  }
  return { ...r, changed, dir };
}
